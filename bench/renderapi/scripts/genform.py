#!/usr/bin/env python3
"""Writes the FormHeavy sources of the bench/renderapi module.

The 40-field form is written out in full in every implementation, as a real
form template would be. This script keeps the KTML source, the templ
baseline, the handwritten lower bound, and the per-tree fixture converters in
step. Run it from bench/renderapi, then regenerate the KTML trees
(go test ./internal/generator/gogen -run RenderAPIBenchmark -update in the
repository root) and the templ code (templ generate ./templ).
"""

import json
import os
import subprocess

FIELDS = 40
ADVERSARIAL_HINT = "Use \"quotes\", <tags> & 'apostrophes'"


def spec(i):
    """The call-site shape of field i (1-based)."""
    kind = {0: "email", 1: None, 2: "tel", 3: "number", 4: "password"}[i % 5]
    hint = None
    if i % 3 == 0:
        hint = ("literal", ADVERSARIAL_HINT)
    elif i % 6 == 1:
        hint = ("dynamic", "help")
    return {
        "name": "f%02d" % i,
        "label": "Field %d <%s> & \"co\"" % (i, kind or "text"),
        "kind": kind,
        "hint": hint,
        "maxlength": 64 if i % 4 == 0 else None,
        "step": 0.5 if kind == "number" else None,
        "required": i % 2 == 0,
        "disabled": i % 7 == 0,
    }


SPECS = [spec(i) for i in range(1, FIELDS + 1)]


def ktml_string(value):
    return json.dumps(value)


def go_string(value):
    return json.dumps(value)


def write(path, content):
    if os.path.dirname(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as output:
        output.write(content)


def ktml_schema():
    fields = "".join("\t%s: string,\n" % s["name"] for s in SPECS)
    return "record FormValues [\n%s\thelp: string,\n]\n" % fields


def ktml_component():
    calls = []
    for s in SPECS:
        args = [
            "name=%s" % ktml_string(s["name"]),
            "label=%s" % ktml_string(s["label"]),
            'value="{values.%s}"' % s["name"],
        ]
        if s["kind"]:
            args.append("kind=%s" % ktml_string(s["kind"]))
        if s["hint"] and s["hint"][0] == "literal":
            args.append("hint=%s" % ktml_string(s["hint"][1]))
        elif s["hint"]:
            args.append('hint="{values.help}"')
        if s["maxlength"] is not None:
            args.append("maxlength=%d" % s["maxlength"])
        if s["step"] is not None:
            args.append("step=%s" % s["step"])
        if s["required"]:
            args.append("required=true")
        if s["disabled"]:
            args.append('disabled="{locked}"')
        calls.append("\t\tField (\n%s\t\t)\n" % "".join("\t\t\t%s\n" % a for a in args))
    return """import { FormValues } from "./form.ktmlschema"

// Code generated by scripts/genform.py. DO NOT EDIT.

// Field is one form field with typed, boolean, optional, and defaulted
// inputs.
Field [name: string, label: string, value: string, kind: string = "text", hint?: string, maxlength: integer = 120, step?: number, required: boolean = false, disabled: boolean = false] {
	div class="field" {
		div class="control" {
			label for="{name}" "{label}"
			input (
				type="{kind}"
				id="{name}"
				name="{name}"
				value="{value}"
				maxlength="{maxlength}"
				required="{required}"
				disabled="{disabled}"
				aria-describedby="{name}-hint"
			)
		}
		if hint? {
			small id="{name}-hint" class="hint" "{hint}"
		}
		div class="extra" {
			if step? {
				span class="step" data-step="{step}" "step"
			}
		}
	}
}

// FormHeavy is the ADR-0003 FormHeavy benchmark: 40 fields whose values carry
// adversarial characters.
FormHeavy [action: URL, csrf: string, values: FormValues, locked: boolean] {
	form (
		method="post"
		action="{action}"
		class="form"
		novalidate
	) {
		input type="hidden" name="csrf" value="{csrf}"
%s		button type="submit" disabled="{locked}" "Save"
	}
}
""" % "".join(calls)


def templ_component():
    calls = []
    for index, s in enumerate(SPECS):
        hint = '""'
        if s["hint"] and s["hint"][0] == "literal":
            hint = go_string(s["hint"][1])
        elif s["hint"]:
            hint = "values.Help"
        step = "0" if s["step"] is None else str(s["step"])
        calls.append(
            "\t\t@TemplField(%s, %s, values.Fields[%d], %s, %s, %d, %s, %s, %s)\n"
            % (
                go_string(s["name"]),
                go_string(s["label"]),
                index,
                go_string(s["kind"] or "text"),
                hint,
                s["maxlength"] or 120,
                step,
                "true" if s["required"] else "false",
                "locked" if s["disabled"] else "false",
            )
        )
    return """// Code generated by scripts/genform.py. DO NOT EDIT.

package tpl

import (
	"strconv"

	"github.com/karl-tye/ktml/bench/renderapi/model"
)

// TemplField is written as idiomatic templ: an empty hint and a zero step
// are absent. The block wrappers keep templ from inserting a space between
// adjacent inline nodes, so the markup matches the other implementations.
templ TemplField(name, label, value, kind, hint string, maxlength int64, step float64, required, disabled bool) {
	<div class="field">
		<div class="control"><label for={ name }>{ label }</label><input type={ kind } id={ name } name={ name } value={ value } maxlength={ strconv.FormatInt(maxlength, 10) } required?={ required } disabled?={ disabled } aria-describedby={ name + "-hint" }></div>
		if hint != "" {
			<small id={ name + "-hint" } class="hint">{ hint }</small>
		}
		<div class="extra">
			if step != 0 {
				<span class="step" data-step={ strconv.FormatFloat(step, 'f', -1, 64) }>step</span>
			}
		</div>
	</div>
}

templ TemplFormHeavy(action string, csrf string, values *model.FormValues, locked bool) {
	<form method="post" action={ templ.URL(action) } class="form" novalidate><input type="hidden" name="csrf" value={ csrf }>
%s		<button type="submit" disabled?={ locked }>Save</button>
	</form>
}
""" % "".join(calls)


def handwritten():
    calls = []
    for index, s in enumerate(SPECS):
        hint = "nil"
        if s["hint"] and s["hint"][0] == "literal":
            hint = "&formHint"
        elif s["hint"]:
            hint = "&values.Help"
        step = "nil" if s["step"] is None else "&formStep"
        calls.append(
            "\tif err := writeField(sw, %s, %s, values.Fields[%d], %s, %s, %d, %s, %s, %s); err != nil {\n\t\treturn err\n\t}\n"
            % (
                go_string(s["name"]),
                go_string(s["label"]),
                index,
                go_string(s["kind"] or "text"),
                hint,
                s["maxlength"] or 120,
                step,
                "true" if s["required"] else "false",
                "locked" if s["disabled"] else "false",
            )
        )
    return """// Code generated by scripts/genform.py. DO NOT EDIT.

package handwritten

import (
	"io"

	"github.com/karl-tye/ktml/bench/renderapi/model"
)

var (
	formHint = %s
	formStep = 0.5
)

// FormHeavy writes the FormHeavy page.
func FormHeavy(w io.Writer, action, csrf string, values *model.FormValues, locked bool) error {
	sw := wrap(w)
	if err := writeFormStart(sw, action, csrf); err != nil {
		return err
	}
%s	return writeFormEnd(sw, locked)
}
""" % (go_string(ADVERSARIAL_HINT), "".join(calls))


def converters():
    out = [
        "// Code generated by scripts/genform.py. DO NOT EDIT.\n\npackage renderapi_test\n\nimport (\n"
        '\taform "github.com/karl-tye/ktml/bench/renderapi/a/form"\n'
        '\tbform "github.com/karl-tye/ktml/bench/renderapi/b/form"\n'
        '\thform "github.com/karl-tye/ktml/bench/renderapi/h/form"\n'
        '\t"github.com/karl-tye/ktml/bench/renderapi/model"\n)\n'
    ]
    for tree in ("h", "b"):
        fields = "".join("\t\t%s: values.Fields[%d],\n" % (s["name"].capitalize(), i) for i, s in enumerate(SPECS))
        out.append(
            "\nfunc %sFormValues(values *model.FormValues) %sform.FormValues {\n\treturn %sform.FormValues{\n%s\t\tHelp: values.Help,\n\t}\n}\n"
            % (tree, tree, tree, fields)
        )
    return "".join(out)


def main():
    write("ktml/form/form.ktmlschema", "// Code generated by scripts/genform.py. DO NOT EDIT.\n\n" + ktml_schema())
    write("ktml/form/form.ktml", ktml_component())
    write("templ/form.templ", templ_component())
    write("handwritten/form_gen.go", handwritten())
    write("form_values_test.go", converters())
    subprocess.run(["gofmt", "-w", "handwritten/form_gen.go", "form_values_test.go"], check=True)


if __name__ == "__main__":
    main()
