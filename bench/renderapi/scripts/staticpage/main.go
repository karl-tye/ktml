// Command staticpage writes the templ and handwritten copies of the Static
// page from the generated KTML renderer, so all three stay byte-identical.
// Run from bench/renderapi: go run ./scripts/staticpage && templ generate -path ./templ
package main

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"strconv"

	hstatic "github.com/karl-tye/ktml/bench/renderapi/h/static"
)

func main() {
	var page bytes.Buffer
	if err := (hstatic.Static{}).Render(context.Background(), &page); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	handwritten := "// Code generated by scripts/staticpage. DO NOT EDIT.\n\npackage handwritten\n\nconst staticPage = " + strconv.Quote(page.String()) + "\n"
	// templ writes static markup verbatim, so the page is one line of HTML.
	templ := "// Code generated by scripts/staticpage. DO NOT EDIT.\n\npackage tpl\n\ntempl Static() {\n\t" + page.String() + "\n}\n"
	for path, content := range map[string]string{"handwritten/static.go": handwritten, "templ/static.templ": templ} {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	fmt.Printf("Static page: %d bytes\n", page.Len())
}
