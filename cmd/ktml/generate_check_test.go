package main

import (
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// snapshotTree returns every file under the working directory and its
// content, so a test can prove a command wrote nothing.
func snapshotTree(t *testing.T) map[string]string {
	t.Helper()
	tree := map[string]string{}
	err := filepath.WalkDir(".", func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		tree[path] = string(mustReadFile(t, path))
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return tree
}

func TestGenerateCmd_GIVENCheck_WHENOutputsAreMissingStaleOrChanged_THENListsThemAndWritesNothing(t *testing.T) {
	writeComponentProject(t, maps.Clone(componentProject))

	before := snapshotTree(t)
	out, err := runGenerate(t, "-check", "./...")
	if err == nil {
		t.Fatalf("generate -check with nothing generated succeeded:\n%s", out)
	}
	for _, want := range []string{"missing: ui/card_ktml.go", "missing: web/page_ktml.go", "missing: web/person_ktmlschema.go"} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	if strings.Contains(out, "_ktml_dev.go") {
		t.Errorf("a missing development output is reported; it is optional:\n%s", out)
	}
	if after := snapshotTree(t); !maps.Equal(before, after) {
		t.Errorf("generate -check wrote files: %v", keysOf(after))
	}

	if _, err := runGenerate(t, "./..."); err != nil {
		t.Fatal(err)
	}
	// A checkout that commits production output and ignores development
	// output has no *_ktml_dev.go files: that is up to date.
	if err := os.Remove("ui/card_ktml_dev.go"); err != nil {
		t.Fatal(err)
	}
	if out, err := runGenerate(t, "-check", "./..."); err != nil || out != "" {
		t.Fatalf("generate -check without development outputs = %q, %v; want no output and no error", out, err)
	}
	if _, err := runGenerate(t, "./..."); err != nil {
		t.Fatal(err)
	}
	if out, err := runGenerate(t, "-check", "./..."); err != nil || out != "" {
		t.Fatalf("generate -check after generate = %q, %v; want no output and no error", out, err)
	}

	// A hand edit, a generated file whose source is gone, and a removed
	// source are each reported; nothing is written.
	if err := os.WriteFile("web/page_ktml.go", []byte("// edited\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	stale := "// Code generated by ktml. DO NOT EDIT.\n\npackage handlers\n"
	if err := os.WriteFile("web/old_ktml.go", []byte(stale), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove("ui/card.ktml"); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("web/page.ktml", []byte("Page [title: string] {\n\tp \"{title}\"\n}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	before = snapshotTree(t)
	out, err = runGenerate(t, "-check", "./...")
	if err == nil {
		t.Fatalf("generate -check with stale outputs succeeded:\n%s", out)
	}
	for _, want := range []string{"changed: web/page_ktml.go", "changed: web/page_ktml_dev.go", "stale: web/old_ktml.go", "stale: ui/card_ktml.go", "stale: ui/card_ktml_dev.go"} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	if strings.Contains(out, "web/person_ktmlschema.go") || strings.Contains(out, "handler.go") {
		t.Errorf("output lists an up-to-date or handwritten file:\n%s", out)
	}
	if after := snapshotTree(t); !maps.Equal(before, after) {
		t.Errorf("generate -check wrote files")
	}
}

func TestGenerateCmd_GIVENCheckWithACachedBuildState_WHENAnOutputIsEdited_THENReportsIt(t *testing.T) {
	writeComponentProject(t, map[string]string{"ui/card.ktml": componentProject["ui/card.ktml"]})
	if _, err := runGenerate(t, "ui"); err != nil {
		t.Fatal(err)
	}
	// The build state still records the old hash: -check must compare
	// bytes, not trust the cache.
	if err := os.WriteFile("ui/card_ktml_dev.go", []byte("// edited\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	out, err := runGenerate(t, "-check", "ui")
	if err == nil || !strings.Contains(out, "changed: ui/card_ktml_dev.go") || !strings.Contains(err.Error(), "1 generated file is out of date") {
		t.Fatalf("generate -check = %q, %v; want the edited development variant", out, err)
	}
}

func keysOf(m map[string]string) []string {
	var keys []string
	for key := range m {
		keys = append(keys, key)
	}
	return keys
}
