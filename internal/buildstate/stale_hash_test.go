package buildstate

import (
	"os"
	"path/filepath"
	"testing"
)

func TestRemove_GIVENAnOutputWithoutARecordedHash_WHENItsSourceIsRemoved_THENTheFileIsKept(t *testing.T) {
	t.Chdir(t.TempDir())
	if err := os.WriteFile("go.mod", []byte("module handwritten\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	state := filepath.Join(".ktml", "state.json")
	if err := os.MkdirAll(".ktml", 0o755); err != nil {
		t.Fatal(err)
	}
	// A crafted or legacy entry names a file KTML never wrote.
	if err := os.WriteFile(state, []byte(`{"files":{"/nowhere/a.ktml":{"hash":"x","primary_output":"go.mod"}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	manifest, err := Load(state)
	if err != nil {
		t.Fatal(err)
	}
	if err := Remove(state, manifest, "/nowhere/a.ktml"); err != nil {
		t.Fatalf("Remove() error = %v", err)
	}
	if content, err := os.ReadFile("go.mod"); err != nil || string(content) != "module handwritten\n" {
		t.Fatalf("go.mod = %q, %v; want it kept", content, err)
	}
}

func TestRemove_GIVENAnOutputEditedSinceGeneration_WHENItsSourceIsRemoved_THENTheEditIsKept(t *testing.T) {
	root := t.TempDir()
	t.Chdir(root)
	state := filepath.Join(".ktml", "state.json")
	manifest, err := Load(state)
	if err != nil {
		t.Fatal(err)
	}
	source := filepath.Join(root, "a.ktml")
	if err := Publish(state, manifest, source, FileEntry{Hash: "h", PrimaryOutput: "a_ktml.go"}, []Output{{Path: "a_ktml.go", Content: []byte("// Code generated by KTML. DO NOT EDIT.\npackage a\n"), Description: "primary output"}}); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("a_ktml.go", []byte("edited by hand"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Remove(state, manifest, source); err != nil {
		t.Fatalf("Remove() error = %v", err)
	}
	if content, err := os.ReadFile("a_ktml.go"); err != nil || string(content) != "edited by hand" {
		t.Fatalf("a_ktml.go = %q, %v; want the edit kept", content, err)
	}
}

func TestRemove_GIVENAnUnchangedOutput_WHENItsSourceIsRemoved_THENTheFileIsDeleted(t *testing.T) {
	root := t.TempDir()
	t.Chdir(root)
	state := filepath.Join(".ktml", "state.json")
	manifest, err := Load(state)
	if err != nil {
		t.Fatal(err)
	}
	source := filepath.Join(root, "a.ktml")
	if err := Publish(state, manifest, source, FileEntry{Hash: "h", PrimaryOutput: "a_ktml.go"}, []Output{{Path: "a_ktml.go", Content: []byte("// Code generated by KTML. DO NOT EDIT.\npackage a\n"), Description: "primary output"}}); err != nil {
		t.Fatal(err)
	}
	if err := Remove(state, manifest, source); err != nil {
		t.Fatalf("Remove() error = %v", err)
	}
	if _, err := os.Stat("a_ktml.go"); !os.IsNotExist(err) {
		t.Fatalf("a_ktml.go stat error = %v; want it deleted", err)
	}
}
