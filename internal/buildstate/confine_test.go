func TestIsGeneratedGo(t *testing.T) {
	for content, want := range map[string]bool{
		"// Code generated by KTML. DO NOT EDIT.\npackage x\n":                     true,
		"//go:build !ktmldev\n\n// Code generated by x. DO NOT EDIT.\npackage x\n": true,
		"package x\n// Code generated by x. DO NOT EDIT.\n":                        false,
		"// Code generated by x.\npackage x\n":                                     false,
		"package x\n":                                                              false,
	} {
		if got := IsGeneratedGo([]byte(content)); got != want {
			t.Errorf("IsGeneratedGo(%q) = %v, want %v", content, got, want)
		}
	}
}
