// craftStaleEntry records path as an output of writer, with a matching hash,
// as a compromised or stale build state would.
func craftStaleEntry(t *testing.T, state, source, writer, path string) *Manifest {
	t.Helper()
	return craftStaleEntryAt(t, state, source, writer, path, path)
}

// craftStaleEntryAt records path with its hash under canonical, the path a
// symlinked parent resolves to, as build state stores it.
func craftStaleEntryAt(t *testing.T, state, source, writer, path, canonical string) *Manifest {
	t.Helper()
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	entry := FileEntry{Hash: "old", PrimaryOutput: filepath.Clean(path), Writer: writer, OutputHashes: map[string]string{filepath.Clean(canonical): Hash(content)}}
	data, err := json.Marshal(Manifest{Files: map[string]FileEntry{source: entry}})
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(state), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(state, data, 0o644); err != nil {
		t.Fatal(err)
	}
	manifest, err := Load(state)
	if err != nil {
		t.Fatal(err)
	}
	return manifest
}

func TestPublishBatch_GIVENStaleCleanupOutsideTheWritersRoots_WHENTheSourceIsRemovedOrRepublished_THENRefusedAndKept(t *testing.T) {
	cases := []struct {
		name, path, want string
	}{
		{"git hook", filepath.Join(".git", "hooks", "pre-commit"), ".git/hooks/pre-commit"},
		{"config", "ktml.config.json", "ktml.config.json"},
		{"KTML source", filepath.Join("views", "page.ktml"), "views/page.ktml"},
		{"prefix lookalike", filepath.Join("generated", "victim.txt"), "generated/victim.txt"},
		{"handwritten Go inside the root", filepath.Join("gen", "handwritten.go"), "gen/handwritten.go"},
	}
	for _, tc := range cases {
		for _, mode := range []string{"removed", "republished"} {
			t.Run(tc.name+"/"+mode, func(t *testing.T) {
				root, state, _ := confinedProject(t)
				if err := os.WriteFile(filepath.Join("generated", "victim.txt"), []byte("keep\n"), 0o644); err != nil {
					t.Fatal(err)
				}
				source := filepath.Join(root, "views", "page.ktml")
				manifest := craftStaleEntry(t, state, source, "evil", tc.path)
				before, _ := os.ReadFile(tc.path)
				var err error
				if mode == "removed" {
					err = PublishBatch(state, manifest, nil, []string{source}, genWriter)
				} else {
					err = publishAs(state, manifest, source, &genWriter, filepath.Join("gen", "fresh.go"))
				}
				if err == nil || !strings.Contains(err.Error(), `plugin "evil"`) || !strings.Contains(err.Error(), tc.want) {
					t.Fatalf("error = %v; want a refusal naming plugin \"evil\" and %s", err, tc.want)
				}
				if after, readErr := os.ReadFile(tc.path); readErr != nil || string(after) != string(before) {
					t.Fatalf("%s = %q, %v; want it kept", tc.path, after, readErr)
				}
				if _, statErr := os.Stat(filepath.Join("gen", "fresh.go")); !os.IsNotExist(statErr) {
					t.Fatalf("fresh output stat error = %v; want the batch rolled back", statErr)
				}
			})
		}
	}
}

