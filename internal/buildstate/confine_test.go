var genWriter = Writer{Name: "evil", Roots: []OutputRoot{{Dir: "gen"}}}

func confinedProject(t *testing.T) (string, string, *Manifest) {
	t.Helper()
	root := t.TempDir()
	t.Chdir(root)
	for _, dir := range []string{"gen", "generated", filepath.Join(".git", "hooks"), "views", ".ktml"} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	for name, content := range map[string]string{
		filepath.Join(".git", "hooks", "pre-commit"): "#!/bin/sh\nexit 0\n",
		"ktml.config.json":                           "{}\n",
		"go.mod":                                     "module example\n",
		filepath.Join("views", "page.ktml"):          "Page { div }\n",
		filepath.Join("gen", "handwritten.go"):       "package gen\n",
	} {
		if err := os.WriteFile(name, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	state := filepath.Join(".ktml", "state.json")
	manifest, err := Load(state)
	if err != nil {
		t.Fatal(err)
	}
	return root, state, manifest
}

func snapshotTree(t *testing.T, root string) map[string]string {
	t.Helper()
	files := map[string]string{}
	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return err
		}
		content, err := os.ReadFile(path)
		files[path] = string(content)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

func publishAs(state string, manifest *Manifest, source string, writer *Writer, path string) error {
	return PublishBatch(state, manifest, []Publication{{
		Source: source,
		Writer: writer,
		Entry:  FileEntry{Hash: "h", PrimaryOutput: path},
		Outputs: []Output{{
			Path:        path,
			Content:     []byte("// Code generated by evil. DO NOT EDIT.\npackage gen\n"),
			Description: "primary output",
		}},
	}}, nil)
}

func TestPublish_GIVENAPluginWriteOutsideItsDeclaredOutputs_WHENPublished_THENRefusedNamingPluginAndPath(t *testing.T) {
	cases := []struct {
		name, path, want string
	}{
		{"git hook", filepath.Join(".git", "hooks", "pre-commit"), ".git/hooks/pre-commit"},
		{"git hook through dot-dot", filepath.Join("gen", "..", ".git", "hooks", "pre-commit"), ".git/hooks/pre-commit"},
		{"build state", filepath.Join(".ktml", "state.json"), ".ktml/state.json"},
		{"config", "ktml.config.json", "ktml.config.json"},
		{"go.mod", "go.mod", "go.mod"},
		{"KTML source", filepath.Join("views", "page.ktml"), "views/page.ktml"},
		{"schema source", filepath.Join("gen", "models.ktmlschema"), "gen/models.ktmlschema"},
		{"story source", filepath.Join("gen", "page.story.ktml"), "gen/page.story.ktml"},
		{"prefix lookalike", filepath.Join("generated", "out.go"), "generated/out.go"},
		{"prefix lookalike sibling", "gen.go", "gen.go"},
		{"handwritten Go inside the root", filepath.Join("gen", "handwritten.go"), "gen/handwritten.go"},
		{"nested .git", filepath.Join("gen", ".git", "config"), "gen/.git/config"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root, state, manifest := confinedProject(t)
			if err := os.MkdirAll(filepath.Join("gen", ".git"), 0o755); err != nil {
				t.Fatal(err)
			}
			before := snapshotTree(t, root)
			err := publishAs(state, manifest, filepath.Join(root, "views", "page.ktml"), &genWriter, tc.path)
			if err == nil {
				t.Fatalf("Publish(%s) succeeded; want a refusal", tc.path)
			}
			if !strings.Contains(err.Error(), `plugin "evil"`) || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("Publish(%s) error = %v; want it to name plugin \"evil\" and %s", tc.path, err, tc.want)
			}
			if after := snapshotTree(t, root); len(after) != len(before) {
				t.Fatalf("files changed: before %d, after %d", len(before), len(after))
			} else {
				for path, content := range before {
					if after[path] != content {
						t.Fatalf("%s changed to %q", path, after[path])
					}
				}
			}
		})
	}
}

func TestPublish_GIVENAPluginWriteThroughASymlinkOutOfItsRoot_WHENPublished_THENRefused(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("symlinks need privileges on Windows")
	}
	root, state, manifest := confinedProject(t)
	if err := os.Symlink(filepath.Join("..", ".git", "hooks"), filepath.Join("gen", "hooks")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join("..", "views"), filepath.Join("gen", "views")); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{filepath.Join("gen", "hooks", "pre-commit"), filepath.Join("gen", "views", "out.go")} {
		err := publishAs(state, manifest, filepath.Join(root, "views", "page.ktml"), &genWriter, path)
		if err == nil || !strings.Contains(err.Error(), `plugin "evil"`) {
			t.Fatalf("Publish(%s) error = %v; want a refusal naming the plugin", path, err)
		}
	}
	if content, _ := os.ReadFile(filepath.Join(".git", "hooks", "pre-commit")); string(content) != "#!/bin/sh\nexit 0\n" {
		t.Fatalf("pre-commit = %q; want it unchanged", content)
	}
	if _, err := os.Stat(filepath.Join("views", "out.go")); !os.IsNotExist(err) {
		t.Fatalf("views/out.go stat error = %v; want no file", err)
	}
}

