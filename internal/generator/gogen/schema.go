package gogen

import (
	"bytes"
	"fmt"
	"path/filepath"
	"sort"

	"github.com/karl-tye/ktml/internal/compiler"
)

// GenerateSchema emits the Go record types declared by one validated
// .ktmlschema document, plus the source map its line directives encode, in
// file order: each generated type, field, constant, and function maps to the
// declaration it was generated from.
func GenerateSchema(snapshot *compiler.Snapshot, file string, options Options) ([]byte, []SourceMapping, error) {
	if snapshot == nil || !snapshot.Valid() {
		return nil, nil, fmt.Errorf("generate: workspace snapshot contains errors")
	}
	if options.Package == "" {
		return nil, nil, fmt.Errorf("generate: package is required")
	}
	path, err := filepath.Abs(file)
	if err != nil {
		return nil, nil, err
	}
	if !compiler.IsSchemaPath(path) || snapshot.Document(path) == nil {
		return nil, nil, fmt.Errorf("generate: %s is not a loaded schema document", file)
	}
	g := &generator{options: options, snapshot: snapshot, file: path, dir: filepath.Dir(path), target: OutputFile(path, false)}
	source := snapshot.Source(path)
	lines := newLineIndex(source)
	var body bytes.Buffer
	type declaration struct {
		start  int
		record *compiler.Record
		state  *compiler.State
	}
	var declarations []declaration
	for _, record := range snapshot.RecordsIn(path) {
		declarations = append(declarations, declaration{start: record.Range.Start, record: &record})
	}
	for _, state := range snapshot.StatesIn(path) {
		declarations = append(declarations, declaration{start: state.Range.Start, state: &state})
	}
	sort.Slice(declarations, func(i, j int) bool { return declarations[i].start < declarations[j].start })
	for _, current := range declarations {
		if current.state != nil {
			if err := g.state(&body, lines, filepath.Base(path), *current.state); err != nil {
				return nil, nil, err
			}
			continue
		}
		record := *current.record
		line, column := lines.lineColumn(record.Range.Start)
		fmt.Fprintf(&body, "// %s is generated from %s:%d:%d.\ntype %s%s struct {\n", record.Name, filepath.Base(path), line, column, g.mark(record.Range), record.Name)
		for _, field := range record.Fields {
			goType, err := g.goType(field.Type)
			if err != nil {
				return nil, nil, fmt.Errorf("record %s field %s: %w", record.Name, field.Name, err)
			}
			if field.Optional {
				goType = "*" + goType
			}
			fmt.Fprintf(&body, "\t%s%s %s\n", g.mark(field.NameRange), field.GoName, goType)
		}
		fmt.Fprint(&body, "}\n\n")
	}
	var output bytes.Buffer
	fmt.Fprintf(&output, "// Code generated by KTML from %s. DO NOT EDIT.\n\npackage %s\n\n", filepath.Base(path), options.Package)
	if len(g.imports) > 0 || g.usesKTML {
		fmt.Fprint(&output, "import (\n")
		if g.usesKTML {
			fmt.Fprint(&output, "\t\"github.com/karl-tye/ktml\"\n")
		}
		writeImports(&output, g.imports)
		fmt.Fprint(&output, ")\n\n")
	}
	output.Write(body.Bytes())
	return g.finish(output.Bytes())
}

// lineIndex holds the line starts of one source, so finding the line and
// byte column of an offset does not rescan the source before it.
type lineIndex struct {
	size   int
	starts []int
}

func newLineIndex(source []byte) lineIndex {
	starts := []int{0}
	for index, char := range source {
		if char == '\n' {
			starts = append(starts, index+1)
		}
	}
	return lineIndex{size: len(source), starts: starts}
}

// lineColumn returns the 1-based line and byte column of offset, clamped to
// the source.
func (index lineIndex) lineColumn(offset int) (int, int) {
	offset = max(0, min(offset, index.size))
	line := sort.Search(len(index.starts), func(i int) bool { return index.starts[i] > offset })
	return line, offset - index.starts[line-1] + 1
}

// state writes a sealed state interface, its discriminator, private Variant
// implementations, payload structs, constructors, and payload accessors.
func (g *generator) state(body *bytes.Buffer, lines lineIndex, file string, state compiler.State) error {
	name := state.Name
	discriminator := name + "Variant"
	line, column := lines.lineColumn(state.Range.Start)
	fmt.Fprintf(body, "// %s is generated from %s:%d:%d. Construct it with the New%s functions;\n// a nil %s is an invalid state.\n", name, file, line, column, name+"*", name)
	fmt.Fprintf(body, "type %s%s interface {\n\t// Variant reports which Variant the state holds.\n\tVariant() %s\n\tis%s()\n}\n\n", g.mark(state.Range), name, discriminator, name)
	fmt.Fprintf(body, "// %s discriminates the Variants of %s. The zero value is no Variant.\ntype %s%s uint8\n\nconst (\n", discriminator, name, g.mark(state.Range), discriminator)
	for index, variant := range state.Variants {
		if index == 0 {
			fmt.Fprintf(body, "\t%s%s%s %s = iota + 1\n", g.mark(variant.Range), discriminator, variant.Name, discriminator)
		} else {
			fmt.Fprintf(body, "\t%s%s%s\n", g.mark(variant.Range), discriminator, variant.Name)
		}
	}
	fmt.Fprint(body, ")\n\n")
	fmt.Fprintf(body, "// String returns the Variant name.\nfunc (v %s) String() string {\n\tswitch v {\n", discriminator)
	for _, variant := range state.Variants {
		fmt.Fprintf(body, "\tcase %s%s:\n\t\treturn %q\n", discriminator, variant.Name, variant.Name)
	}
	fmt.Fprintf(body, "\t}\n\treturn %q\n}\n\n", discriminator+"(invalid)")
	for _, variant := range state.Variants {
		private := "ktml" + name + variant.Name
		line, column := lines.lineColumn(variant.Range.Start)
		if !variant.Payload {
			fmt.Fprintf(body, "type %s struct{}\n\n", private)
			fmt.Fprintf(body, "func (%s) Variant() %s { return %s%s }\nfunc (%s) is%s() {}\n\n", private, discriminator, discriminator, variant.Name, private, name)
			fmt.Fprintf(body, "// New%s%s returns %s.%s, generated from %s:%d:%d.\nfunc %sNew%s%s() %s { return %s{} }\n\n", name, variant.Name, name, variant.Name, file, line, column, g.mark(variant.Range), name, variant.Name, name, private)
			continue
		}
		payload := name + variant.Name
		fmt.Fprintf(body, "// %s is the payload of %s.%s, generated from %s:%d:%d.\ntype %s%s struct {\n", payload, name, variant.Name, file, line, column, g.mark(variant.Range), payload)
		for _, field := range variant.Fields {
			goType, err := g.goType(field.Type)
			if err != nil {
				return fmt.Errorf("state %s Variant %s field %s: %w", name, variant.Name, field.Name, err)
			}
			if field.Optional {
				goType = "*" + goType
			}
			fmt.Fprintf(body, "\t%s%s %s\n", g.mark(field.NameRange), field.GoName, goType)
		}
		fmt.Fprint(body, "}\n\n")
		fmt.Fprintf(body, "type %s struct{ payload %s }\n\n", private, payload)
		fmt.Fprintf(body, "func (%s) Variant() %s { return %s%s }\nfunc (%s) is%s() {}\n\n", private, discriminator, discriminator, variant.Name, private, name)
		fmt.Fprintf(body, "// New%s returns %s.%s with payload.\nfunc %sNew%s(payload %s) %s { return %s{payload: payload} }\n\n", payload, name, variant.Name, g.mark(variant.Range), payload, payload, name, private)
		fmt.Fprintf(body, "// As%s returns the payload of %s.%s and whether state holds that Variant.\nfunc %sAs%s(state %s) (%s, bool) {\n\tvariant, ok := state.(%s)\n\treturn variant.payload, ok\n}\n\n", payload, name, variant.Name, g.mark(variant.Range), payload, name, payload, private)
	}
	return nil
}
