// Package storygen writes stories for components: values synthesized from
// their input types (`ktml stories generate`) or captured from a running
// application (`ktml dev --capture-stories`). Both write story Documents
// through Merge, which keeps every story a person wrote or edited.
package storygen

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/karl-tye/ktml/dev/interp"
	"github.com/karl-tye/ktml/internal/ast"
	"github.com/karl-tye/ktml/internal/compiler"
	"github.com/karl-tye/ktml/internal/parser"
)

// GeneratedHeader comments a story Document the generator creates.
var GeneratedHeader = []string{
	"Stories generated by `ktml stories generate` from the components' input types.",
	"A story below a `// ktml:generated <hash>` line is rewritten while its text still",
	"matches the hash; edit it and the generator keeps your version. Stories you add",
	"are never touched.",
}

// Options configure a generation run.
type Options struct {
	// Components are the components to write stories for.
	Components []compiler.Component
	// Comments returns the comment lines above a component's first story,
	// such as the routes that reach it.
	Comments func(compiler.Component) []string
	// Page reports a page, a component a route's handler renders, which
	// gets only its Default or Variant stories.
	Page func(compiler.Component) bool
	// Accumulate keeps the generated stories of components that are not
	// planned, so stories can be added one component at a time.
	Accumulate bool
}

// File is the outcome for one story Document.
type File struct {
	Path    string
	Source  []byte
	Before  []byte
	Report  FileReport
	Changed bool
}

// Skipped is a component without generated stories.
type Skipped struct {
	Component compiler.Component
	Reason    string
}

// Result is a planned generation run. Nothing is written until Write.
type Result struct {
	Files   []File
	Skipped []Skipped
	// Stories counts the generated stories; Variants and Covered the
	// distinct Variants of the states in the components' input types and
	// those some story selects.
	Stories  int
	Variants int
	Covered  int
	// Warnings are diagnostics outside generated blocks, such as errors in
	// hand-written stories, which do not stop a run.
	Warnings []string
}

// StoryPath is the story Document of a component Document: x.ktml has
// x.story.ktml beside it.
func StoryPath(componentFile string) string {
	return strings.TrimSuffix(componentFile, ".ktml") + ".story.ktml"
}

// Plan synthesizes the stories of every component, merges them into the
// story Documents on disk, and verifies the result: every generated story
// type-checks with no diagnostic and renders.
func Plan(root string, snapshot *compiler.Snapshot, options Options) (Result, error) {
	var result Result
	byFile := make(map[string][]compiler.Component)
	var files []string
	for _, component := range options.Components {
		if _, ok := byFile[component.File]; !ok {
			files = append(files, component.File)
		}
		byFile[component.File] = append(byFile[component.File], component)
	}
	sort.Strings(files)
	variants := make(map[compiler.SymbolID]bool)
	covered := make(map[compiler.SymbolID]bool)
	for _, file := range files {
		components := byFile[file]
		sort.Slice(components, func(i, j int) bool { return components[i].Range.Start < components[j].Range.Start })
		path := StoryPath(file)
		before, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return result, err
		}
		if err != nil {
			before = nil
		}
		fixtures := newFixtureNames(before)
		s := &synthesizer{snapshot: snapshot, fixture: fixtures.name}
		desired := Desired{Header: GeneratedHeader, Accumulate: options.Accumulate}
		var names []string
		for _, component := range components {
			synthesis := s.synthesize(component, options.Page != nil && options.Page(component))
			if synthesis.Skipped != "" {
				result.Skipped = append(result.Skipped, Skipped{Component: component, Reason: synthesis.Skipped})
				continue
			}
			for id := range synthesis.Variants {
				variants[id] = true
			}
			for id := range synthesis.Covered {
				covered[id] = true
			}
			names = append(names, component.Name)
			for index, story := range synthesis.Stories {
				text, err := StoryText(story)
				if err != nil {
					return result, err
				}
				block := Block{Key: component.Name + "." + story.Name, Text: text}
				if index == 0 && options.Comments != nil {
					block.Comments = options.Comments(component)
				}
				desired.Stories = append(desired.Stories, block)
				result.Stories++
			}
		}
		if len(names) == 0 {
			continue
		}
		desired.Imports = []Import{{Path: "./" + filepath.Base(file), Names: names}}
		desired.Fixtures = fixtures.declarations()
		source, report, err := Merge(before, desired, GeneratedMarker)
		if err != nil {
			return result, fmt.Errorf("%s: %w", path, err)
		}
		result.Files = append(result.Files, File{Path: path, Source: source, Before: before, Report: report, Changed: !bytes.Equal(source, before)})
	}
	result.Variants = len(variants)
	for id := range covered {
		if variants[id] {
			result.Covered++
		}
	}
	if err := verify(root, result.Files, GeneratedMarker, &result.Warnings); err != nil {
		return result, err
	}
	return result, nil
}

// ComponentErrors reports the first error outside story Documents. Stories
// are generated from component and schema Documents, so errors in stories,
// such as stale generated stories after a schema change, do not stop a run.
func ComponentErrors(snapshot *compiler.Snapshot) error {
	var messages []string
	for _, file := range snapshot.Files() {
		if compiler.IsStoryPath(file) {
			continue
		}
		for _, diagnostic := range snapshot.Diagnostics(file) {
			if diagnostic.Severity == compiler.SeverityError {
				line, column := lineColumn(string(snapshot.Source(file)), diagnostic.Start)
				messages = append(messages, fmt.Sprintf("%s:%d:%d: [%s] %s", file, line, column, diagnostic.Code, diagnostic.Message))
			}
		}
	}
	if len(messages) > 0 {
		return fmt.Errorf("the components have errors:\n%s", strings.Join(messages, "\n"))
	}
	return nil
}

// Write writes the changed story Documents.
func (r Result) Write() error {
	for _, file := range r.Files {
		if !file.Changed {
			continue
		}
		if err := os.WriteFile(file.Path, file.Source, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// fixtureNames resolves the fixture a Document's stories use for each
// trusted type: the placeholder, unless the Document already declares that
// name with another type.
type fixtureNames struct {
	existing map[string]string
	used     map[string]FixtureDecl
}

func newFixtureNames(source []byte) *fixtureNames {
	names := &fixtureNames{existing: make(map[string]string), used: make(map[string]FixtureDecl)}
	if source == nil {
		return names
	}
	document := parser.New(source).ParseDocument()
	for _, node := range document.Nodes {
		if fixture, ok := node.(*ast.FixtureDecl); ok {
			names.existing[fixture.Name] = fixture.TypeDecl
		}
	}
	return names
}

func (f *fixtureNames) name(typeName string) string {
	if declared, ok := f.used[typeName]; ok {
		return declared.Name
	}
	placeholder := placeholderFixtures[typeName]
	name := placeholder.name
	for suffix := 2; f.existing[name] != "" && f.existing[name] != typeName; suffix++ {
		name = fmt.Sprintf("%s%d", placeholder.name, suffix)
	}
	f.used[typeName] = FixtureDecl{Name: name, Type: typeName, Value: placeholder.value}
	return name
}

func (f *fixtureNames) declarations() []FixtureDecl {
	list := make([]FixtureDecl, 0, len(f.used))
	for _, declared := range f.used {
		list = append(list, declared)
	}
	sort.Slice(list, func(i, j int) bool { return list[i].Name < list[j].Name })
	return list
}

// verify type-checks the planned Documents with the rest of the workspace
// and renders every story under the marker. A diagnostic or render error in
// a marked block fails the run; diagnostics elsewhere are warnings.
func verify(root string, files []File, marker string, warnings *[]string) error {
	workspace := compiler.NewWorkspace(root)
	for _, file := range files {
		if err := workspace.Overlay(file.Path, 1, file.Source); err != nil {
			return err
		}
	}
	snapshot, err := workspace.Index()
	if err != nil {
		return err
	}
	var failures []string
	marked := make(map[string]bool)
	for _, file := range files {
		text := string(file.Source)
		p := parser.New(file.Source)
		blocks := scan(text, p.ParseDocument(), marker)
		inBlock := func(offset int) bool {
			for _, block := range blocks {
				if block.marked && block.intact && offset >= block.start && offset <= block.end {
					return true
				}
			}
			return false
		}
		for _, block := range blocks {
			if block.kind == "story" && block.marked && block.intact {
				marked[string(storyIDOf(file.Path, block.key))] = true
			}
		}
		for _, diagnostic := range snapshot.Diagnostics(file.Path) {
			line, column := lineColumn(text, diagnostic.Start)
			message := fmt.Sprintf("%s:%d:%d: [%s] %s", file.Path, line, column, diagnostic.Code, diagnostic.Message)
			if diagnostic.Severity == compiler.SeverityError && inBlock(diagnostic.Start) {
				failures = append(failures, message)
			} else {
				*warnings = append(*warnings, message)
			}
		}
	}
	if len(failures) > 0 {
		return fmt.Errorf("generated stories do not type-check:\n%s", strings.Join(failures, "\n"))
	}
	if !snapshot.Valid() {
		*warnings = append(*warnings, "the workspace has errors, so generated stories were not rendered")
		return nil
	}
	program, err := interp.New(snapshot, interp.Options{})
	if err != nil {
		*warnings = append(*warnings, fmt.Sprintf("generated stories were not rendered: %v", err))
		return nil
	}
	for _, story := range snapshot.Stories() {
		if !marked[string(story.ID)] {
			continue
		}
		if err := program.RenderStory(context.Background(), io.Discard, story.ID, nil); err != nil {
			failures = append(failures, fmt.Sprintf("%s: story %s.%s: %v", story.File, story.ComponentName, story.Name, err))
		}
	}
	if len(failures) > 0 {
		return fmt.Errorf("generated stories do not render:\n%s", strings.Join(failures, "\n"))
	}
	return nil
}

func storyIDOf(path, key string) compiler.SymbolID {
	canonical, err := filepath.Abs(path)
	if err != nil {
		canonical = path
	}
	return compiler.SymbolID(filepath.Clean(canonical) + "::story::" + key)
}
